-- New event-key notifications bypass the legacy ten-minute same-target dedupe;
-- the unique partial index makes exact duplicate attempts idempotent.
create unique index if not exists notifications_order_event_key_unique
on public.notifications(user_id,(data->>'event_key')) where (data ? 'event_key');
create or replace function public.hayna_dedupe_new_notifications() returns trigger
language plpgsql set search_path=pg_catalog as $$
begin
 if new.data ? 'event_key' then return new; end if;
 if new.target_id is not null and new.target_type is not null and exists(
 select 1 from public.notifications n where n.user_id=new.user_id and n.type=new.type
 and n.target_type=new.target_type and n.target_id=new.target_id
 and n.read_at is null and n.created_at>now()-interval '10 minutes'
 ) then return null;end if;
 return new;
end $$;

create or replace function app_private.hayna_order_emit_notification(p_user uuid,p_type text,p_target uuid,p_title text,p_body text,p_key text) returns void
language plpgsql security definer set search_path=pg_catalog as $$
declare v_in_app boolean;v_push boolean;
begin
 if p_user is null then return;end if;
 select coalesce(np.in_app_enabled,true),coalesce(np.push_enabled,true) into v_in_app,v_push
 from (select 1) x left join public.order_notification_preferences np on np.user_id=p_user;
 if not v_in_app then return;end if;
 select v_push and not coalesce(dnd_enabled,false) into v_push from public.profiles where id=p_user;
 insert into public.notifications(user_id,type,title,body,target_type,target_id,data)
 values(p_user,p_type,p_title,p_body,'order',p_target,jsonb_build_object('event_key',p_key,'push_allowed',coalesce(v_push,false),'order_id',p_target))
 on conflict do nothing;
end $$;
revoke all on function app_private.hayna_order_emit_notification(uuid,text,uuid,text,text,text) from public,anon,authenticated;

create or replace function app_private.hayna_order_status_event() returns trigger
language plpgsql security definer set search_path=pg_catalog as $$
declare v_buyer uuid;v_seller uuid;v_kind text;v_status text;v_text text;v_target uuid;v_key text;
begin
 if old.status is not distinct from new.status then return new;end if;
 if tg_table_name='marketplace_service_orders' then
  v_buyer:=new.buyer_id;v_seller:=new.provider_id;v_kind:='service';
  insert into public.order_status_history(service_order_id,actor_id,old_status,new_status)
  values(new.id,auth.uid(),old.status,new.status);
 else
  v_buyer:=new.buyer_id;v_seller:=new.seller_id;v_kind:='product';
  insert into public.order_status_history(product_request_id,actor_id,old_status,new_status)
  values(new.id,auth.uid(),old.status,new.status);
 end if;
 v_status:=new.status;
 v_text:=case v_status when 'accepted' then 'تم قبول طلبك' when 'rejected' then 'اعتذر البائع عن قبول الطلب'
 when 'ready' then 'طلبك جاهز للاستلام' when 'completed' then 'تم تأكيد استلام الطلب وإكماله'
 when 'in_progress' then 'بدأ تنفيذ طلبك' when 'cancelled' then 'تم إلغاء الطلب'
 when 'refunded' then 'تم استرداد المبلغ' when 'paid' then 'تم تأكيد دفع الطلب'
 else 'تم تحديث حالة الطلب' end;
 v_key:='order:'||v_kind||':'||new.id::text||':'||v_status||':'||
   case when v_kind='service' then new.updated_at::text else new.version::text end;
 if v_buyer is distinct from auth.uid() then
  perform app_private.hayna_order_emit_notification(v_buyer,'order_status',new.id,'تحديث طلب السوق',v_text,v_key||':buyer');
 end if;
 if v_seller is distinct from auth.uid() then
  perform app_private.hayna_order_emit_notification(v_seller,'order_status',new.id,'تحديث طلب السوق',v_text,v_key||':seller');
 end if;
 return new;
end $$;
revoke all on function app_private.hayna_order_status_event() from public,anon,authenticated;
create trigger hayna_service_order_status_event after update of status on public.marketplace_service_orders
 for each row execute function app_private.hayna_order_status_event();
create trigger hayna_product_order_status_event after update of status on public.marketplace_product_requests
 for each row execute function app_private.hayna_order_status_event();

