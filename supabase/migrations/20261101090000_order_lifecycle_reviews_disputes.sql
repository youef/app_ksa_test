
-- Hayna marketplace order lifecycle, verified reviews, private disputes.
-- Additive migration; existing payment workflow and marketplace request tables retained.
create table if not exists public.order_notification_preferences(
  user_id uuid primary key references auth.users(id) on delete cascade,
  in_app_enabled boolean not null default true,
  push_enabled boolean not null default true,
  updated_at timestamptz not null default now()
);
alter table public.order_notification_preferences enable row level security;
grant select,insert,update on public.order_notification_preferences to authenticated;
create policy order_notification_prefs_select on public.order_notification_preferences for select to authenticated using(user_id=(select auth.uid()));
create policy order_notification_prefs_insert on public.order_notification_preferences for insert to authenticated with check(user_id=(select auth.uid()));
create policy order_notification_prefs_update on public.order_notification_preferences for update to authenticated using(user_id=(select auth.uid())) with check(user_id=(select auth.uid()));

create table if not exists public.order_status_history(
 id uuid primary key default gen_random_uuid(),
 service_order_id uuid references public.marketplace_service_orders(id) on delete cascade,
 product_request_id uuid references public.marketplace_product_requests(id) on delete cascade,
 actor_id uuid references auth.users(id) on delete set null,
 old_status text, new_status text not null, note text,
 created_at timestamptz not null default now(),
 constraint order_status_history_single_order check(num_nonnulls(service_order_id,product_request_id)=1)
);
create index if not exists order_history_service_idx on public.order_status_history(service_order_id,created_at desc);
create index if not exists order_history_product_idx on public.order_status_history(product_request_id,created_at desc);

create table if not exists public.order_reviews(
 id uuid primary key default gen_random_uuid(),
 service_order_id uuid unique references public.marketplace_service_orders(id) on delete cascade,
 product_request_id uuid unique references public.marketplace_product_requests(id) on delete cascade,
 buyer_id uuid not null references auth.users(id) on delete cascade,
 seller_id uuid not null references auth.users(id) on delete cascade,
 rating integer not null check(rating between 1 and 5),
 body text not null default '' check(char_length(body)<=2000),
 photo_paths text[] not null default '{}'::text[] check(coalesce(array_length(photo_paths,1),0)<=3),
 moderation_status text not null default 'approved' check(moderation_status in ('approved','hidden')),
 created_at timestamptz not null default now(),
 constraint order_reviews_single_order check(num_nonnulls(service_order_id,product_request_id)=1)
);
create index if not exists order_reviews_seller_idx on public.order_reviews(seller_id,moderation_status,created_at desc);

create table if not exists public.review_replies(
 id uuid primary key default gen_random_uuid(),
 review_id uuid not null unique references public.order_reviews(id) on delete cascade,
 seller_id uuid not null references auth.users(id) on delete cascade,
 body text not null check(char_length(trim(body)) between 1 and 2000),
 created_at timestamptz not null default now(),
 updated_at timestamptz not null default now()
);
create table if not exists public.review_reports(
 id uuid primary key default gen_random_uuid(),
 review_id uuid not null references public.order_reviews(id) on delete cascade,
 reporter_id uuid not null references auth.users(id) on delete cascade,
 reason text not null check(char_length(trim(reason)) between 5 and 1000),
 status text not null default 'open' check(status in ('open','reviewing','resolved','dismissed')),
 admin_note text,
 created_at timestamptz not null default now(),
 unique(review_id,reporter_id)
);

create table if not exists public.order_disputes(
 id uuid primary key default gen_random_uuid(),
 ticket_number bigint generated by default as identity unique,
 service_order_id uuid references public.marketplace_service_orders(id) on delete cascade,
 product_request_id uuid references public.marketplace_product_requests(id) on delete cascade,
 requester_id uuid not null references auth.users(id) on delete cascade,
 category text not null check(category in ('delay','quality','not_received','incorrect_details','payment','other')),
 description text not null check(char_length(trim(description)) between 10 and 3000),
 status text not null default 'open' check(status in ('open','reviewing','awaiting_customer','resolved','closed')),
 admin_note text,
 created_at timestamptz not null default now(),
 updated_at timestamptz not null default now(),
 constraint order_disputes_single_order check(num_nonnulls(service_order_id,product_request_id)=1)
);
create index if not exists order_disputes_requester_idx on public.order_disputes(requester_id,created_at desc);
create index if not exists order_disputes_service_idx on public.order_disputes(service_order_id,created_at desc);
create index if not exists order_disputes_product_idx on public.order_disputes(product_request_id,created_at desc);

create table if not exists public.dispute_messages(
 id uuid primary key default gen_random_uuid(),
 dispute_id uuid not null references public.order_disputes(id) on delete cascade,
 sender_id uuid not null references auth.users(id) on delete cascade,
 is_admin boolean not null default false,
 body text not null check(char_length(trim(body)) between 1 and 3000),
 created_at timestamptz not null default now()
);
create index if not exists dispute_messages_ticket_idx on public.dispute_messages(dispute_id,created_at);
create table if not exists public.dispute_attachments(
 id uuid primary key default gen_random_uuid(),
 dispute_id uuid not null references public.order_disputes(id) on delete cascade,
 uploader_id uuid not null references auth.users(id) on delete cascade,
 storage_path text not null unique check(char_length(storage_path) between 10 and 500),
 created_at timestamptz not null default now()
);
create index if not exists dispute_attachments_ticket_idx on public.dispute_attachments(dispute_id);

create or replace function public.hayna_order_is_party(p_kind text,p_id uuid,p_user uuid default auth.uid()) returns boolean
language sql stable security definer set search_path=pg_catalog as $$
 select p_user is not null and p_user=(select auth.uid()) and
 ( (p_kind='service' and exists(select 1 from public.marketplace_service_orders s where s.id=p_id and p_user in(s.buyer_id,s.provider_id)))
 or (p_kind='product' and exists(select 1 from public.marketplace_product_requests r where r.id=p_id and p_user in(r.buyer_id,r.seller_id))) );
$$;
revoke all on function public.hayna_order_is_party(text,uuid,uuid) from public,anon;
grant execute on function public.hayna_order_is_party(text,uuid,uuid) to authenticated;

create or replace function app_private.hayna_guard_order_review() returns trigger
language plpgsql security definer set search_path=pg_catalog as $$
declare v_buyer uuid;v_seller uuid;v_status text;v_uid uuid:=auth.uid(); v_path text;
begin
 if tg_op <> 'INSERT' or v_uid is null then raise exception 'review_write_not_allowed' using errcode='42501';end if;
 if new.service_order_id is not null then
  select buyer_id,provider_id,status into v_buyer,v_seller,v_status from public.marketplace_service_orders where id=new.service_order_id;
 elsif new.product_request_id is not null then
  select buyer_id,seller_id,status into v_buyer,v_seller,v_status from public.marketplace_product_requests where id=new.product_request_id;
 else raise exception 'order_required' using errcode='22023';end if;
 if v_buyer is null or v_buyer<>v_uid or v_status<>'completed'
 then raise exception 'confirmed_receipt_required' using errcode='42501';end if;
 foreach v_path in array coalesce(new.photo_paths,'{}'::text[]) loop
  if v_path not like v_uid::text||'/%' or position('..' in v_path)>0 then raise exception 'invalid_review_photo_path' using errcode='22023';end if;
 end loop;
 new.buyer_id:=v_buyer;new.seller_id:=v_seller;new.moderation_status:='approved';new.created_at:=now();
 return new;
end $$;
revoke all on function app_private.hayna_guard_order_review() from public,anon,authenticated;
create trigger hayna_guard_order_review before insert on public.order_reviews
for each row execute function app_private.hayna_guard_order_review();

create or replace function app_private.hayna_guard_review_reply() returns trigger
language plpgsql security definer set search_path=pg_catalog as $$
declare v_seller uuid;begin
 if tg_op='INSERT' then
   select seller_id into v_seller from public.order_reviews where id=new.review_id;
   if v_seller is null or v_seller<>auth.uid() then raise exception 'seller_only' using errcode='42501';end if;
   new.seller_id:=v_seller;new.created_at:=now();new.updated_at:=now();
 else
   if old.seller_id is distinct from auth.uid() or new.review_id is distinct from old.review_id or new.seller_id is distinct from old.seller_id or new.created_at is distinct from old.created_at then
    raise exception 'reply_immutable_fields' using errcode='42501';end if;
   new.updated_at:=now();
 end if;
 return new;
end $$;
revoke all on function app_private.hayna_guard_review_reply() from public,anon,authenticated;
create trigger hayna_guard_review_reply before insert or update on public.review_replies for each row execute function app_private.hayna_guard_review_reply();

create or replace function app_private.hayna_guard_dispute() returns trigger
language plpgsql security definer set search_path=pg_catalog as $$
begin
 if tg_op='INSERT' then
  if auth.uid() is null or new.requester_id<>auth.uid() then raise exception 'requester_only' using errcode='42501';end if;
  if new.service_order_id is not null then
   if not exists(select 1 from public.marketplace_service_orders s where s.id=new.service_order_id and auth.uid() in(s.buyer_id,s.provider_id)) then raise exception 'order_access_denied' using errcode='42501';end if;
  elsif new.product_request_id is not null then
   if not exists(select 1 from public.marketplace_product_requests r where r.id=new.product_request_id and auth.uid() in(r.buyer_id,r.seller_id)) then raise exception 'order_access_denied' using errcode='42501';end if;
  else raise exception 'order_required' using errcode='22023';end if;
  new.status:='open';new.admin_note:=null;new.created_at:=now();new.updated_at:=now();
 else
  if new.requester_id is distinct from old.requester_id or new.service_order_id is distinct from old.service_order_id or new.product_request_id is distinct from old.product_request_id
    or new.description is distinct from old.description or new.category is distinct from old.category
  then raise exception 'immutable_ticket_details' using errcode='42501';end if;
  new.updated_at:=now();
 end if;
 return new;
end $$;
revoke all on function app_private.hayna_guard_dispute() from public,anon,authenticated;
create trigger hayna_guard_order_dispute before insert or update on public.order_disputes for each row execute function app_private.hayna_guard_dispute();

