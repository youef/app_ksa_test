create or replace function public.hayna_order_mark_ready(p_order uuid) returns void
language plpgsql security definer set search_path=pg_catalog as $$
begin
 if auth.uid() is null or not exists(select 1 from public.profiles p where p.id=auth.uid() and not coalesce(p.is_banned,false)) then raise exception 'authentication_required' using errcode='42501';end if;
 update public.marketplace_service_orders set status='ready',updated_at=now()
 where id=p_order and provider_id=auth.uid() and status='in_progress';
 if not found then raise exception 'invalid_transition_or_permission' using errcode='42501';end if;
end $$;
revoke all on function public.hayna_order_mark_ready(uuid) from public,anon;
grant execute on function public.hayna_order_mark_ready(uuid) to authenticated;
create or replace function public.hayna_order_confirm_received(p_order uuid) returns void
language plpgsql security definer set search_path=pg_catalog as $$
begin
 if auth.uid() is null or not exists(select 1 from public.profiles p where p.id=auth.uid() and not coalesce(p.is_banned,false)) then raise exception 'authentication_required' using errcode='42501';end if;
