create or replace function app_private.hayna_review_reply_notify() returns trigger
language plpgsql security definer set search_path=pg_catalog as $$
declare v_buyer uuid;begin
 select buyer_id into v_buyer from public.order_reviews where id=new.review_id;
 perform app_private.hayna_order_emit_notification(v_buyer,'review_reply',new.review_id,'رد البائع على تقييمك','رد البائع على تقييم الطلب','review_reply:'||new.id::text);
 return new;end $$;
revoke all on function app_private.hayna_review_reply_notify() from public,anon,authenticated;
create trigger hayna_review_reply_notify after insert on public.review_replies for each row execute function app_private.hayna_review_reply_notify();

-- Avoid sending two Push requests for new order notifications, while preserving legacy types.
drop trigger if exists notifications_dispatch_push on public.notifications;
create trigger notifications_dispatch_push after insert on public.notifications for each row
 when (new.type not in ('order_status','dispute_reply','review_reply'))
 execute function public.dispatch_push_notification();
drop trigger if exists notifications_push_after_insert on public.notifications;
create trigger notifications_push_after_insert after insert on public.notifications for each row
 when (new.type not in ('order_status','dispute_reply','review_reply') or (new.data->>'push_allowed')='true')
 execute function public.send_notification_push();

create or replace view public.order_seller_rating_summary with(security_invoker=true) as
select seller_id,count(*)::integer as review_count,round(avg(rating)::numeric,2) as average_rating
from public.order_reviews where moderation_status='approved' group by seller_id;
grant select on public.order_seller_rating_summary to authenticated;

